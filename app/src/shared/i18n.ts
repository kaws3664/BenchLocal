export function normalizeLocale(value: unknown): BenchLocalLocale {
  return value === "en-US" || value === "en" ? "en-US" : "zh-CN";
}

export function translate(locale: BenchLocalLocale, key: string, ...args: unknown[]): string {
  const base = key.includes("~") ? key.slice(0, key.indexOf("~")) : key;
  let fmt = locale === "en-US" ? (EN_MESSAGES[key] ?? EN_MESSAGES[base] ?? base) : base;
  if (args.length > 0) {
    fmt = fmt.replace(/\{(\d+)\}/g, (match, index) => {
      const value = args[Number(index)];
      return value === undefined || value === null ? match : String(value);
    });
  }
  return fmt;
}

// 主进程侧的当前语言（菜单、对话框使用）。
let processLocale: BenchLocalLocale = "zh-CN";

export function getProcessLocale(): BenchLocalLocale {
  return processLocale;
}

export function setProcessLocale(value: unknown): void {
  processLocale = normalizeLocale(value);
}

export function tProcess(key: string, ...args: unknown[]): string {
  return translate(processLocale, key, ...args);
}
